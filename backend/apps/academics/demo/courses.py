"""Katalog demo: empat mata kuliah, masing-masing 12 sesi dengan satu materi dan satu tugas.

Satu sesi = satu pertemuan mingguan. Tiap tugas membawa "slot" yang dipakai generator jawaban
(`demo/answers.py`) untuk menulis jawaban yang sesuai topiknya:

- topic: frasa benda topik (huruf kecil);
- c: empat konsep kunci;
- ex: kasus konkret yang dibahas;
- pick / alt: pendekatan yang dipilih dan pembandingnya;
- why: alasan memilih (anak kalimat setelah "karena").

kind menentukan bentuk jawaban: "esai", "kode" (ada blok kode), "tautan" (menyertakan tautan
hasil kerja), atau "dokumen" (dosen mengizinkan unggah PDF). Semua tautan materi bisa dibuka.
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Session:
    topic: str
    material: tuple[str, str, str]  # judul, ringkasan, tautan ("" = catatan dosen)
    title: str
    instructions: str
    bloom: int
    kind: str
    slots: dict
    code: str = ""
    requirements: tuple[str, ...] = field(default_factory=tuple)


@dataclass(frozen=True)
class Course:
    label: str
    teacher: str  # kunci dosen di TEACHERS
    name: str
    subject: str
    # Berapa hari lalu pertemuan ke-10 berlangsung: kelas jatuh di hari berbeda dalam sepekan.
    day_offset: int
    graded_through: int  # tugas 1..n sudah dinilai semua
    partially_graded: tuple[int, ...]  # sebagian sudah dinilai
    sessions: tuple[Session, ...]


